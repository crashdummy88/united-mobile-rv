#!/usr/bin/env node
// Regenerates functions/_lib/guide-urls.js from the static guide/ tree so
// functions/sitemap.xml.js can list every guide page. Pages Functions cannot
// read the repo filesystem at runtime, so the list is baked in at commit time.
// Run after adding or removing a guide:  node scripts/gen-guide-urls.mjs
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const lastmod = (p) => {
  try { return execSync(`git log -1 --format=%cs -- "${p}"`, { cwd: root }).toString().trim() || null; } catch { return null; }
};
const entries = [{ path: '/guide/', lastmod: lastmod('guide/index.html') }];
for (const name of readdirSync(join(root, 'guide')).sort()) {
  const dir = join(root, 'guide', name);
  if (!statSync(dir).isDirectory()) continue;
  try { statSync(join(dir, 'index.html')); } catch { continue; }
  entries.push({ path: `/guide/${name}/`, lastmod: lastmod(`guide/${name}/index.html`) });
}
const out = `// Generated by scripts/gen-guide-urls.mjs -- do not edit by hand.\n` +
  `export const GUIDE_URLS = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(join(root, 'functions/_lib/guide-urls.js'), out);
console.log(`wrote ${entries.length} guide URLs`);
